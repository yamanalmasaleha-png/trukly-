function fold(s) {
  return String(s || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

export default async function(req, res) {
  const raw = String(req.query?.q || "").trim();
  const q = fold(raw);
  const limit = Math.max(1, Math.min(50, +req.query?.limit || 20));
  const matched = q
    ? catalog.filter(t => fold([t.name, t.cuisine, ...(t.tags || []), t.city, t.location].join(" ")).includes(q))
    : catalog;
  res.json({
    query: raw.toLowerCase(),
    total: matched.length,
    results: matched.slice(0, limit).map(({ id, name, cuisine, city, location }) => ({ id, name, cuisine, city, location }))
  });
}
